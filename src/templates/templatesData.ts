import {
  ALL_STATIONERY_TEMPLATES,
  GIFT_TAG_TEMPLATES,
  MENU_TEMPLATES,
  PLACE_CARD_TEMPLATES,
  THANK_YOU_TEMPLATES,
} from './stationeryData';

export const ALL_TEMPLATES: TemplateConfig[] = [
  ...INVITATION_TEMPLATES,
  ...WISHES_TEMPLATES,
  ...ALL_STATIONERY_TEMPLATES,
];

export function getTemplateById(id: string): TemplateConfig {
  return ALL_TEMPLATES.find((t) => t.id === id) || INVITATION_TEMPLATES[0];
}

export function getTemplatesByCategory(category: CardCategory): TemplateConfig[] {
  switch (category) {
    case 'invitation':
      return INVITATION_TEMPLATES;
    case 'wishes':
      return WISHES_TEMPLATES;
    case 'menu':
      return MENU_TEMPLATES;
    case 'place-card':
      return PLACE_CARD_TEMPLATES;
    case 'gift-tag':
      return GIFT_TAG_TEMPLATES;
    case 'thank-you':
      return THANK_YOU_TEMPLATES;
  }
}
